-- KYO Sushi - esquema inicial Supabase
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  is_admin boolean not null default false,
  reward_points integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.branches (
  id text primary key,
  name text not null,
  short_name text not null,
  address text not null,
  phone text,
  eta text,
  active boolean not null default true
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  sort_order integer not null default 0,
  active boolean not null default true
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  category_id uuid references public.categories(id) on delete set null,
  image_url text,
  featured boolean not null default false,
  spicy boolean not null default false,
  available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null default 'Dirección',
  address_line text not null,
  notes text,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  user_id uuid not null references public.profiles(id) on delete restrict,
  branch_id text not null references public.branches(id),
  fulfillment_type text not null check (fulfillment_type in ('delivery','pickup')),
  delivery_address text,
  delivery_notes text,
  payment_method text not null default 'cash',
  status text not null default 'received' check (status in ('received','accepted','preparing','ready','on_the_way','delivered','cancelled')),
  subtotal numeric(10,2) not null,
  delivery_fee numeric(10,2) not null default 0,
  total numeric(10,2) not null,
  rewards_awarded boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(10,2) not null,
  quantity integer not null check (quantity > 0)
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.profiles p where p.id = uid and p.is_admin = true);
$$;

create or replace function public.create_order(
  p_branch_id text,
  p_fulfillment_type text,
  p_delivery_address text,
  p_delivery_notes text,
  p_payment_method text,
  p_items jsonb
)
returns table(id uuid, order_number bigint, total numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_order_id uuid;
  v_order_number bigint;
  v_subtotal numeric(10,2) := 0;
  v_delivery_fee numeric(10,2) := 0;
  v_total numeric(10,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if v_user is null then raise exception 'Debes iniciar sesión'; end if;
  if p_fulfillment_type not in ('delivery','pickup') then raise exception 'Tipo de entrega inválido'; end if;
  if p_fulfillment_type = 'delivery' and coalesce(trim(p_delivery_address),'') = '' then raise exception 'Falta dirección de entrega'; end if;
  if jsonb_array_length(coalesce(p_items,'[]'::jsonb)) = 0 then raise exception 'El carrito está vacío'; end if;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := greatest(1, least(20, coalesce((v_item->>'quantity')::int,1)));
    select * into v_product from public.products
      where id = (v_item->>'product_id')::uuid and available = true;
    if not found then raise exception 'Uno de los productos ya no está disponible'; end if;
    v_subtotal := v_subtotal + (v_product.price * v_qty);
  end loop;

  v_delivery_fee := case when p_fulfillment_type='delivery' then 39 else 0 end;
  v_total := v_subtotal + v_delivery_fee;

  insert into public.orders(user_id,branch_id,fulfillment_type,delivery_address,delivery_notes,payment_method,subtotal,delivery_fee,total)
  values(v_user,p_branch_id,p_fulfillment_type,p_delivery_address,p_delivery_notes,p_payment_method,v_subtotal,v_delivery_fee,v_total)
  returning public.orders.id, public.orders.order_number into v_order_id, v_order_number;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := greatest(1, least(20, coalesce((v_item->>'quantity')::int,1)));
    select * into v_product from public.products where id = (v_item->>'product_id')::uuid;
    insert into public.order_items(order_id,product_id,product_name,unit_price,quantity)
    values(v_order_id,v_product.id,v_product.name,v_product.price,v_qty);
  end loop;

  return query select v_order_id, v_order_number, v_total;
end;
$$;

revoke all on function public.create_order(text,text,text,text,text,jsonb) from public;
grant execute on function public.create_order(text,text,text,text,text,jsonb) to authenticated;

create or replace function public.award_rewards_on_delivery()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.status = 'delivered' and old.status is distinct from 'delivered' and new.rewards_awarded = false then
    update public.profiles
      set reward_points = reward_points + floor(new.subtotal)::int,
          updated_at = now()
      where id = new.user_id;
    new.rewards_awarded := true;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists orders_award_rewards on public.orders;
create trigger orders_award_rewards
before update on public.orders
for each row execute procedure public.award_rewards_on_delivery();

