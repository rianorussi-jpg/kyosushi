-- Lectura pública del catálogo
create policy "branches public read" on public.branches for select using (active = true or public.is_admin(auth.uid()));
create policy "categories public read" on public.categories for select using (active = true or public.is_admin(auth.uid()));
create policy "products public read" on public.products for select using (available = true or public.is_admin(auth.uid()));

-- Perfil
create policy "profile own read" on public.profiles for select using (auth.uid() = id or public.is_admin(auth.uid()));
create policy "profile own update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id and is_admin = false);
create policy "admins manage profiles" on public.profiles for all using (public.is_admin(auth.uid())) with check (public.is_admin(auth.uid()));

-- Direcciones
create policy "addresses own select" on public.addresses for select using (auth.uid() = user_id or public.is_admin(auth.uid()));
create policy "addresses own insert" on public.addresses for insert with check (auth.uid() = user_id);
create policy "addresses own update" on public.addresses for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "addresses own delete" on public.addresses for delete using (auth.uid() = user_id);

-- Pedidos
create policy "orders own select" on public.orders for select using (auth.uid() = user_id or public.is_admin(auth.uid()));
create policy "admins update orders" on public.orders for update using (public.is_admin(auth.uid())) with check (public.is_admin(auth.uid()));
create policy "order items own select" on public.order_items for select using (
  exists(select 1 from public.orders o where o.id = order_id and (o.user_id = auth.uid() or public.is_admin(auth.uid())))
);

-- Admin catálogo
create policy "admins manage branches" on public.branches for all using (public.is_admin(auth.uid())) with check (public.is_admin(auth.uid()));
create policy "admins manage categories" on public.categories for all using (public.is_admin(auth.uid())) with check (public.is_admin(auth.uid()));
create policy "admins manage products" on public.products for all using (public.is_admin(auth.uid())) with check (public.is_admin(auth.uid()));

